#!/bin/bash
# Maintainer step (login node, network): resolve SET-common.in + SET-MACHINE.in for
# CPython 3.12 on MACHINE and write requirements-SET-MACHINE.txt with one sha256
# per wheel. Usage: lock.sh SET MACHINE   (SET build|validate, MACHINE aarch64|x86_64)
set -Eeuo pipefail
set_=$1 machine=$2; here=$(cd "$(dirname "$0")" && pwd)
case $set_ in build|validate) ;; *) echo "SET must be build or validate" >&2; exit 2 ;; esac
case $machine in aarch64|x86_64) ;; *) echo "MACHINE must be aarch64 or x86_64" >&2; exit 2 ;; esac
tmp=$(mktemp -d); trap 'rm -rf "$tmp"' EXIT
platform=(--only-binary=:all: --implementation cp --python-version 3.12 --abi cp312)
for tag in manylinux_2_34 manylinux_2_28 manylinux_2_27 manylinux_2_24 manylinux_2_17 manylinux2014; do
  platform+=(--platform "${tag}_$machine"); done
python3.12 -m pip download -q "${platform[@]}" -d "$tmp" -r "$here/$set_-common.in" -r "$here/$set_-$machine.in"
python3.12 - "$tmp" "$here/requirements-$set_-$machine.txt" "$set_" "$machine" <<'PY'
import hashlib, pathlib, re, sys
tmp, out, s, m = pathlib.Path(sys.argv[1]), sys.argv[2], sys.argv[3], sys.argv[4]
rows = {}
for w in sorted(tmp.glob("*.whl")):
    name, ver = w.name.split("-")[:2]
    name = re.sub(r"[-_.]+", "-", name).lower()
    rows.setdefault((name, ver), []).append(hashlib.sha256(w.read_bytes()).hexdigest())
lines = [f"# Generated by lock.sh {s} {m} for CPython 3.12; install with",
         "# pip install --no-index --require-hashes --find-links <wheelhouse> -r <this file>"]
for (n, v), hs in sorted(rows.items()):
    lines.append(f"{n}=={v} " + " ".join(f"--hash=sha256:{h}" for h in hs))
pathlib.Path(out).write_text("\n".join(lines) + "\n")
PY
echo "wrote requirements-$set_-$machine.txt"
